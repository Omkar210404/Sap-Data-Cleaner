"""End-to-end: generate the synthetic sample data, run the real CLI on it as a
subprocess, and check the output files against what the generator injected."""

import csv
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

from sap_cleaner.config import load_reference

ROOT = Path(__file__).resolve().parent.parent
CASES = {
    "material": {"file": "materials", "id": "MATNR", "width": 18, "date": "ERSDA", "key": ["MATNR", "WERKS"]},
    "vendor": {"file": "vendors", "id": "LIFNR", "width": 10, "date": "ERDAT", "key": ["LIFNR"]},
}
# Generator defect name -> text the cleaner's reject reason must contain.
EXPECTED_REASON = {
    "unknown_unit": "is not a known unit of measure",
    "unknown_country": "is not a known country code",
    "invalid_date": "is not a valid date",
    "invalid_id": "contains characters that are not allowed",
    "exact_duplicate": "exact duplicate of row {of_row}",
    "key_conflict": "as row {of_row} but different",
    "near_duplicate": "near-duplicate of row {of_row} (",
}


def run(*args):
    return subprocess.run([sys.executable, *args], cwd=ROOT, capture_output=True, text=True)


def run_cli(*args):
    return run("-m", "sap_cleaner", *args)


def read_csv(path, delimiter=","):
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle, delimiter=delimiter))


@pytest.fixture(scope="module")
def sample_dir(tmp_path_factory):
    """Fresh synthetic sample data, generated by the real script."""
    out = tmp_path_factory.mktemp("synthetic")
    done = run("scripts/generate_sample_data.py", "--out", str(out))
    assert done.returncode == 0, done.stderr
    return out


@pytest.fixture(scope="module", params=CASES)
def case(request, sample_dir, tmp_path_factory):
    """One CLI run per data type, shared by the tests below."""
    spec = CASES[request.param]
    out = tmp_path_factory.mktemp(f"out_{request.param}")
    source = sample_dir / f"{spec['file']}.csv"
    done = run_cli("clean", "--input", str(source), "--type", request.param, "--out", str(out))
    assert done.returncode == 0, done.stderr
    return {
        **spec,
        "type": request.param,
        "out": out,
        "stdout": done.stdout,
        "manifest": json.loads((sample_dir / "manifest.json").read_text(encoding="utf-8"))[spec["file"]],
        "input": read_csv(source),
        "cleaned": read_csv(out / f"{spec['file']}_cleaned.csv"),
        "rejected": read_csv(out / f"{spec['file']}_rejected.csv"),
        "changes": read_csv(out / f"{spec['file']}_changes.csv"),
        "report": (out / f"{spec['file']}_report.txt").read_text(encoding="utf-8"),
    }


def test_every_input_row_ends_up_cleaned_or_rejected(case):
    assert len(case["input"]) == case["manifest"]["rows"]
    assert len(case["cleaned"]) + len(case["rejected"]) == len(case["input"])
    assert case["cleaned"] and case["rejected"]


def test_exactly_the_rows_with_injected_reject_defects_are_rejected(case):
    expected = {entry["row"] for entry in case["manifest"]["expected_rejects"]}
    assert {int(row["SOURCE_ROW"]) for row in case["rejected"]} == expected


def test_each_rejected_row_gives_the_reason_for_every_injected_defect(case):
    reasons = {int(row["SOURCE_ROW"]): row["REJECT_REASONS"].split("; ") for row in case["rejected"]}
    for entry in case["manifest"]["expected_rejects"]:
        found = reasons[entry["row"]]
        assert len(found) == len(entry["defects"]), (entry, found)
        for defect in entry["defects"]:
            if defect.startswith("missing_"):
                wanted = f"{defect.removeprefix('missing_')} is blank"
            else:
                wanted = EXPECTED_REASON[defect].format(of_row=entry.get("of_row"))
            assert any(wanted in reason for reason in found), (entry, found)


def test_lookalike_rows_that_are_not_duplicates_survive(case):
    rejected = {int(row["SOURCE_ROW"]) for row in case["rejected"]}
    assert case["manifest"]["must_survive_rows"]
    assert not rejected & set(case["manifest"]["must_survive_rows"])


def test_rejected_rows_are_written_back_as_they_were_in_the_input(case):
    for row in case["rejected"]:
        original = case["input"][int(row["SOURCE_ROW"]) - 2]
        assert {column: row[column] for column in original} == original


def test_cleaned_ids_keep_their_leading_zeros(case):
    for row in case["cleaned"]:
        value = row[case["id"]]
        assert re.fullmatch(rf"[0-9]{{{case['width']}}}|[A-Z]+-[0-9]+", value), value
    assert any(row[case["id"]].startswith("0") for row in case["cleaned"])


def test_cleaned_values_are_standardised(case):
    reference = load_reference()
    for row in case["cleaned"]:
        assert all(value == " ".join(value.split()) for value in row.values()), row
        assert re.fullmatch(r"\d{4}-\d{2}-\d{2}|", row[case["date"]]), row
        if case["type"] == "material":
            assert row["MEINS"] in reference["units_of_measure"]["valid"]
            assert row["GEWEI"] in reference["units_of_measure"]["valid"] | {""}
            assert all(row[c] for c in ("MATNR", "MAKTX", "MTART", "MATKL", "MEINS", "WERKS"))
        else:
            assert row["LAND1"] in reference["countries"]["valid"]
            assert all(row[c] for c in ("LIFNR", "NAME1", "ORT01", "LAND1", "KTOKK", "ZTERM"))


def test_cleaned_file_has_no_duplicate_keys(case):
    keys = [tuple(row[column] for column in case["key"]) for row in case["cleaned"]]
    assert len(keys) == len(set(keys))


def test_change_log_explains_every_difference_between_input_and_cleaned(case):
    rejected = {int(row["SOURCE_ROW"]) for row in case["rejected"]}
    kept_rows = [number for number in range(2, len(case["input"]) + 2) if number not in rejected]
    final = {}
    for change in case["changes"]:
        cell = (int(change["SOURCE_ROW"]), change["COLUMN"])
        # Chained changes to one cell must link up: each starts where the last ended.
        assert change["OLD_VALUE"] == final.get(cell, case["input"][cell[0] - 2][cell[1]])
        final[cell] = change["NEW_VALUE"]
    assert not {row for row, _ in final} & rejected
    for number, cleaned in zip(kept_rows, case["cleaned"], strict=True):
        for column, value in cleaned.items():
            assert value == final.get((number, column), case["input"][number - 2][column])


def test_report_and_console_numbers_match_the_files(case):
    counts = {"Read": len(case["input"]), "Cleaned": len(case["cleaned"]),
              "Rejected": len(case["rejected"]), "Total": len(case["changes"])}
    for label, count in counts.items():
        assert re.search(rf"^  {label}\s+{count}$", case["report"], re.MULTILINE), label
    assert f"Read {len(case['input'])} rows" in case["stdout"]
    assert re.search(rf"cleaned\s+{len(case['cleaned'])} rows", case["stdout"])
    assert re.search(rf"rejected\s+{len(case['rejected'])} rows", case["stdout"])


def test_cleaning_the_cleaned_file_again_changes_nothing(case, tmp_path):
    cleaned_path = case["out"] / f"{case['file']}_cleaned.csv"
    done = run_cli("clean", "--input", str(cleaned_path), "--type", case["type"], "--out", str(tmp_path))
    assert done.returncode == 0, done.stderr
    stem = f"{case['file']}_cleaned"
    assert read_csv(tmp_path / f"{stem}_rejected.csv") == []
    assert read_csv(tmp_path / f"{stem}_changes.csv") == []
    assert (tmp_path / f"{stem}_cleaned.csv").read_bytes() == cleaned_path.read_bytes()


def test_semicolon_delimited_input_gives_the_same_result(case, sample_dir, tmp_path):
    source = tmp_path / f"{case['file']}.csv"
    with open(source, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(case["input"][0]), delimiter=";")
        writer.writeheader()
        writer.writerows(case["input"])
    out = tmp_path / "out"
    done = run_cli("clean", "--input", str(source), "--type", case["type"], "--out", str(out), "--delimiter", ";")
    assert done.returncode == 0, done.stderr
    assert read_csv(out / f"{case['file']}_cleaned.csv", delimiter=";") == case["cleaned"]
    assert read_csv(out / f"{case['file']}_rejected.csv", delimiter=";") == case["rejected"]


def test_committed_sample_files_match_the_generator(sample_dir):
    for name in ("materials.csv", "vendors.csv", "manifest.json"):
        committed = (ROOT / "data" / "synthetic" / name).read_text(encoding="utf-8")
        assert committed == (sample_dir / name).read_text(encoding="utf-8"), name


