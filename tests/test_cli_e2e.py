def test_missing_input_file_exits_1(tmp_path):
    done = run_cli("clean", "--input", str(tmp_path / "nope.csv"), "--type", "vendor", "--out", str(tmp_path))
    assert done.returncode == 1
    assert "Input error: input file not found" in done.stderr
    assert "Traceback" not in done.stderr


def test_wrong_data_type_for_the_file_exits_1(sample_dir, tmp_path):
    done = run_cli("clean", "--input", str(sample_dir / "vendors.csv"), "--type", "material", "--out", str(tmp_path))
    assert done.returncode == 1
    assert "missing columns the rules need: MATNR" in done.stderr
    assert list(tmp_path.iterdir()) == []


def test_bad_rules_file_exits_2(sample_dir, tmp_path):
    rules = tmp_path / "rules.yaml"
    rules.write_text("columns: [LIFNR]\nrules:\n  trimm: {}\n", encoding="utf-8")
    done = run_cli("clean", "--input", str(sample_dir / "vendors.csv"), "--type", "vendor",
                   "--out", str(tmp_path / "out"), "--config", str(rules))
    assert done.returncode == 2
    assert "Config error: unknown rule 'trimm'" in done.stderr
    assert "Traceback" not in done.stderr


def test_unknown_type_is_a_usage_error():
    done = run_cli("clean", "--input", "x.csv", "--type", "customer", "--out", "out")
    assert done.returncode == 2
    assert "invalid choice" in done.stderr


def test_custom_rules_file_changes_the_behaviour(sample_dir, tmp_path):
    # Same data, one line of YAML different: dates come out in SAP's internal format.
    rules = tmp_path / "rules.yaml"
    built_in = (ROOT / "sap_cleaner" / "config" / "vendor.yaml").read_text(encoding="utf-8")
    assert 'output_format: "%Y-%m-%d"' in built_in
    rules.write_text(built_in.replace('output_format: "%Y-%m-%d"', 'output_format: "%Y%m%d"'), encoding="utf-8")
    out = tmp_path / "out"
    done = run_cli("clean", "--input", str(sample_dir / "vendors.csv"), "--type", "vendor",
                   "--out", str(out), "--config", str(rules))
    assert done.returncode == 0, done.stderr
    dates = [row["ERDAT"] for row in read_csv(out / "vendors_cleaned.csv")]
    assert all(re.fullmatch(r"\d{8}|", value) for value in dates)
    assert any(dates)
